-- 몬스터 공격 테이블
CREATE TABLE MON_ATK (
    MON_ATK_NO NUMBER NOT NULL,        -- 몬스터 공격 패턴 번호 (PK)
    MON_ATK_NAME VARCHAR2(100) NOT NULL, -- 패턴 설명
    MON_EFFECT NUMBER NOT NULL,        -- 수치 계산용 값
    MON_HIT_RANGE NUMBER NOT NULL,     -- 공격 범위 계산용 값
    ATK_TYPE NUMBER NOT NULL,          -- 공격 방식 (FK)
    CONSTRAINT PK_MON_ATK PRIMARY KEY (MON_ATK_NO),
    CONSTRAINT FK_MON_ATK_TYPE FOREIGN KEY (ATK_TYPE) REFERENCES ATK_PATTERN(ATK_TYPE)
);

-- 몬스터 도감 테이블
CREATE TABLE MONSTER (
    MON_NO NUMBER NOT NULL,            -- 몬스터 고유 번호 (PK)
    MON_NAME CHAR(30) NOT NULL,        -- 몬스터 이름
    MON_DIF NUMBER NOT NULL,           -- 난이도 설정값
    MON_SPEED NUMBER NOT NULL,         -- 턴 순서용 속도값
    MON_HP NUMBER NOT NULL,            -- 최대 체력
    MON_EFFECT NUMBER NOT NULL,        -- 기본 효과값 (치유/공격)
    MON_IMG VARCHAR2(250) NOT NULL,    -- 출력할 이미지 경로
    MON_ATK_NO NUMBER NOT NULL,        -- 몬스터 공격 패턴 (FK)
    CONSTRAINT PK_MONSTER PRIMARY KEY (MON_NO),
    CONSTRAINT FK_MON_PATTERN FOREIGN KEY (MON_ATK_NO) REFERENCES MON_ATK(MON_ATK_NO)
);

-- 공격 방식 테이블
CREATE TABLE ATK_PATTERN (
    ATK_TYPE NUMBER NOT NULL,           -- 공격 방식 ID (PK)
    ATK_NAME CHAR(100) NOT NULL,        -- 공격 방식 이름/설명
    
    CONSTRAINT PK_ATK_PATTERN PRIMARY KEY (ATK_TYPE)
);

